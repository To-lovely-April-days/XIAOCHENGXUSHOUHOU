using Huotong.AfterSales.Api.Services;
using Xunit;

public class FileSniffTests
{
    [Theory]
    [InlineData(new byte[] { 0xFF, 0xD8, 0xFF, 0xE0, 0, 0, 0, 0, 0, 0, 0, 0 }, "image/jpeg")]
    [InlineData(new byte[] { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A }, "image/png")]
    [InlineData(new byte[] { 0x47, 0x49, 0x46, 0x38, 0x39, 0x61 }, "image/gif")]
    [InlineData(new byte[] { 0x52, 0x49, 0x46, 0x46, 0, 0, 0, 0, 0x57, 0x45, 0x42, 0x50 }, "image/webp")]
    [InlineData(new byte[] { 0, 0, 0, 0x18, 0x66, 0x74, 0x79, 0x70, 0x68, 0x65, 0x69, 0x63 }, "image/heic")]
    [InlineData(new byte[] { 0, 0, 0, 0x18, 0x66, 0x74, 0x79, 0x70, 0x69, 0x73, 0x6F, 0x6D }, "video/mp4")]
    // v1.2：HEIC 新品牌、不以 ftyp 开头的 QuickTime；PDF / OLE / ZIP 头不是图片视频
    [InlineData(new byte[] { 0, 0, 0, 0x18, 0x66, 0x74, 0x79, 0x70, 0x68, 0x65, 0x69, 0x78 }, "image/heic")] // heix
    [InlineData(new byte[] { 0, 0, 0, 0x18, 0x66, 0x74, 0x79, 0x70, 0x6D, 0x69, 0x66, 0x31 }, "image/heic")] // mif1
    [InlineData(new byte[] { 0, 0, 0, 0x18, 0x66, 0x74, 0x79, 0x70, 0x68, 0x65, 0x76, 0x63 }, "image/heic")] // hevc
    [InlineData(new byte[] { 0, 0, 0, 0x18, 0x66, 0x74, 0x79, 0x70, 0x68, 0x65, 0x69, 0x6D }, "image/heic")] // heim
    [InlineData(new byte[] { 0, 0, 0, 0x18, 0x66, 0x74, 0x79, 0x70, 0x68, 0x65, 0x69, 0x73 }, "image/heic")] // heis
    [InlineData(new byte[] { 0, 0, 0, 0x18, 0x66, 0x74, 0x79, 0x70, 0x6D, 0x73, 0x66, 0x31 }, "image/heic")] // msf1
    [InlineData(new byte[] { 0, 0, 0, 0x14, 0x66, 0x74, 0x79, 0x70, 0x71, 0x74, 0x20, 0x20 }, "video/quicktime")] // ftyp qt
    [InlineData(new byte[] { 0, 0, 0, 0x08, 0x6D, 0x6F, 0x6F, 0x76 }, "video/quicktime")] // moov
    [InlineData(new byte[] { 0, 0, 0, 0x08, 0x6D, 0x64, 0x61, 0x74 }, "video/quicktime")] // mdat
    [InlineData(new byte[] { 0, 0, 0, 0x08, 0x77, 0x69, 0x64, 0x65 }, "video/quicktime")] // wide
    [InlineData(new byte[] { 0, 0, 0, 0x08, 0x66, 0x72, 0x65, 0x65 }, "video/quicktime")] // free
    [InlineData(new byte[] { 0, 0, 0, 0x08, 0x73, 0x6B, 0x69, 0x70 }, "video/quicktime")] // skip
    [InlineData(new byte[] { 0x42, 0x4D, 0, 0 }, "image/bmp")]
    [InlineData(new byte[] { 0x25, 0x50, 0x44, 0x46, 0x2D, 0x31, 0x2E, 0x34 }, null)] // %PDF-1.4
    [InlineData(new byte[] { 0xD0, 0xCF, 0x11, 0xE0, 0xA1, 0xB1, 0x1A, 0xE1 }, null)] // OLE
    [InlineData(new byte[] { 0x50, 0x4B, 0x03, 0x04, 0x14, 0, 0, 0 }, null)] // ZIP
    [InlineData(new byte[] { 0x3C, 0x73, 0x76, 0x67, 0x20 }, null)] // <svg
    [InlineData(new byte[] { 0x25, 0x50, 0x44, 0x46 }, null)]
    [InlineData(new byte[] { }, null)]
    public void SniffMime_ByMagicBytes(byte[] head, string? expected)
        => Assert.Equal(expected, FileService.SniffMime(head));
}
